const resourceGroup = (group: string, extra = '') => `scmProvider == git && scmResourceGroup == ${group}${extra}`
const mixed = ' && config.git.untrackedChanges == mixed'
const notMixed = ' && config.git.untrackedChanges != mixed'
const inlineOpen = ' && config.git.showInlineOpenFileAction && config.git.openDiffOnClick'
const inlineChange = ' && config.git.showInlineOpenFileAction && !config.git.openDiffOnClick'

function resourceItems(group: string, items: [string, string, string?][]): MenuItem[] {
  return items.map(([command, groupName, extra]) => ({ command, group: groupName, when: resourceGroup(group, extra ?? '') }))
}

