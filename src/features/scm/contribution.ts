const category = { text: 'Git' }
const busy = '!operationInProgress'

function command(id: string, extra: Partial<CommandContribution> = {}): CommandContribution {
  return { command: id, title: { vs: `command.${id.slice(4)}` }, category, enablement: busy, ...extra }
}

